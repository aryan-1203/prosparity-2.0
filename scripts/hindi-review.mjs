// Writes docs/HINDI_REVIEW.md from the message files. Run: node scripts/hindi-review.mjs
import { readFileSync, writeFileSync } from "node:fs";

const load = (l) => JSON.parse(readFileSync(`apps/web/messages/${l}.json`, "utf8"));
const flat = (value, path = "", out = {}) => {
  if (typeof value === "string") out[path] = value;
  else for (const [k, v] of Object.entries(value)) flat(v, path ? `${path}.${k}` : k, out);
  return out;
};
const en = flat(load("en"));
const hi = flat(load("hi"));
const cell = (s) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
const rows = Object.keys(en).filter((k) => en[k] && hi[k]);
const body = rows.map((k) => `| \`${k}\` | ${cell(en[k])} | ${cell(hi[k])} |  |`).join("\n");
writeFileSync(
  "docs/HINDI_REVIEW.md",
  `# Hindi review\n\nEvery translated string, for a native speaker to review before launch. None have been reviewed by a native speaker yet. ${rows.length} strings. Generated by \`scripts/hindi-review.mjs\`.\n\n| Key | English | Hindi | Reviewer note |\n| --- | --- | --- | --- |\n${body}\n`,
);
console.log(rows.length, "strings");
