#!/usr/bin/env python3
"""Turns a TopoJSON of Indian states into small SVG paths for the Network map.

Usage: python3 -I scripts/build-india-map.py <india.json> <out.ts>
Arcs are simplified once and shared, so neighbouring states keep identical borders.
"""
import json, math, sys

src, out = sys.argv[1], sys.argv[2]
topo = json.load(open(src))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]

arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx
        y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)

WIDTH = 600
PAD = 6
COS = math.cos(math.radians(22))
lons = [p[0] for a in arcs for p in a]
lats = [p[1] for a in arcs for p in a]
scale = (WIDTH - 2 * PAD) / ((max(lons) - min(lons)) * COS)
HEIGHT = round((max(lats) - min(lats)) * scale + 2 * PAD)


def project(lon, lat):
    return ((lon - min(lons)) * COS * scale + PAD, (max(lats) - lat) * scale + PAD)


def simplify(points, tolerance):
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = points[a], points[b]
        length = math.hypot(bx - ax, by - ay) or 1e-9
        best, index = 0.0, None
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs((bx - ax) * (ay - py) - (ax - px) * (by - ay)) / length
            if d > best:
                best, index = d, i
        if index is not None and best > tolerance:
            keep[index] = True
            stack += [(a, index), (index, b)]
    return [p for p, k in zip(points, keep) if k]


TOLERANCE = 1.1
flat = [simplify([project(*p) for p in a], TOLERANCE) for a in arcs]


def ring(indices):
    pts = []
    for i in indices:
        seg = flat[i] if i >= 0 else list(reversed(flat[~i]))
        pts += seg if not pts else seg[1:]
    return pts


def path(rings):
    parts = []
    for r in rings:
        if len(r) < 3:
            continue
        parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in r) + "Z")
    return "".join(parts)


CENTRES = {"Madhya Pradesh": "mp", "Uttar Pradesh": "up", "Chhattisgarh": "cg"}
centres = {}
states = []
for geometry in topo["objects"]["states"]["geometries"]:
    arcs_ = geometry["arcs"]
    polygons = [arcs_] if geometry["type"] == "Polygon" else arcs_
    rings = [ring(r) for polygon in polygons for r in polygon]
    name = geometry["properties"]["st_nm"]
    states.append((name, path(rings)))
    if name in CENTRES:
        pts = max(rings, key=len)
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        centres[CENTRES[name]] = {"x": round((min(xs) + max(xs)) / 2 / WIDTH * 100, 1), "y": round((min(ys) + max(ys)) / 2 / HEIGHT * 100, 1)}
states.sort()

bx, by = project(77.41, 23.26)
with open(out, "w") as f:
    f.write("/** Generated by scripts/build-india-map.py. Do not edit by hand. */\n")
    f.write(f"export const MAP_WIDTH = {WIDTH};\nexport const MAP_HEIGHT = {HEIGHT};\n")
    f.write(f"export const BHOPAL = {{ x: {bx:.1f}, y: {by:.1f} }};\n\n")
    f.write(f"/** Centre of each operating state, as a percentage of the map. */\nexport const CENTRES = {json.dumps(centres)};\n\n")
    f.write("export const statePaths: readonly (readonly [string, string])[] = [\n")
    for name, d in states:
        f.write(f"  [{json.dumps(name)}, {json.dumps(d)}],\n")
    f.write("];\n")
print(WIDTH, HEIGHT, sum(len(d) for _, d in states), "bytes of path data")
